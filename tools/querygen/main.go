// querygen derives query validation rules from the vendored OpenAPI contract.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
)

type schema struct {
	Type      string   `json:"type"`
	Enum      []any    `json:"enum"`
	Minimum   *float64 `json:"minimum"`
	Maximum   *float64 `json:"maximum"`
	MinLength *int     `json:"minLength"`
	MaxLength *int     `json:"maxLength"`
	Items     *schema  `json:"items"`
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	data, err := os.ReadFile("resources/openapi/nebula-openapi.json")
	if err != nil {
		return err
	}
	var spec struct {
		Paths map[string]map[string]struct {
			ID         string `json:"operationId"`
			Parameters []struct {
				Name     string `json:"name"`
				In       string `json:"in"`
				Required bool   `json:"required"`
				Explode  *bool  `json:"explode"`
				Schema   schema `json:"schema"`
			} `json:"parameters"`
		} `json:"paths"`
	}
	if err := json.Unmarshal(data, &spec); err != nil {
		return err
	}
	paths := make([]string, 0, len(spec.Paths))
	for path := range spec.Paths {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.\n\npackage nebula\n\nvar queryRules = map[string][]queryRule{")
	for _, path := range paths {
		op, ok := spec.Paths[path]["get"]
		if !ok {
			continue
		}
		fmt.Fprintf(&out, "%q: {\n", op.ID)
		for _, p := range op.Parameters {
			if p.In != "query" || p.Name == "locale" {
				continue
			} // Locale stays extensible.
			s := p.Schema
			fmt.Fprintf(&out, "{name: %q, required: %t,", p.Name, p.Required)
			if s.Type == "array" {
				fmt.Fprintf(&out, "csv: %t,", p.Explode != nil && !*p.Explode)
				if s.Items != nil {
					s = *s.Items
				}
			}
			fmt.Fprintf(&out, "kind: %q,", s.Type)
			if len(s.Enum) > 0 {
				fmt.Fprint(&out, "enum: []string{")
				for _, e := range s.Enum {
					fmt.Fprintf(&out, "%q,", fmt.Sprint(e))
				}
				fmt.Fprint(&out, "},")
			}
			if s.Minimum != nil {
				fmt.Fprintf(&out, "min: Float64Ptr(%v),", *s.Minimum)
			}
			if s.Maximum != nil {
				fmt.Fprintf(&out, "max: Float64Ptr(%v),", *s.Maximum)
			}
			if s.MinLength != nil {
				fmt.Fprintf(&out, "minLength: %d,", *s.MinLength)
			}
			if s.MaxLength != nil {
				fmt.Fprintf(&out, "maxLength: %d,", *s.MaxLength)
			}
			fmt.Fprintln(&out, "},")
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("validation_rules.go", formatted, 0644)
}
