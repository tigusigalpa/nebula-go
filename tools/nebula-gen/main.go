// nebula-gen generates the Nebula SDK surface from the pinned OpenAPI contract.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type operationNames struct {
	Group           string `json:"group"`
	Service         string `json:"service"`
	Method          string `json:"method"`
	Request         string `json:"request"`
	Response        string `json:"response"`
	StandaloneClass bool   `json:"standalone_class"`
}

type enumNames struct {
	Constants map[string]string `json:"constants"`
}

// Only Go naming decisions belong here; field schemas always come from OpenAPI.
type compatibility struct {
	Operations map[string]operationNames `json:"operations"`
	Objects    map[string]string         `json:"objects"`
	Scalars    map[string]string         `json:"scalars"`
	Fields     map[string]string         `json:"fields"`
	Enums      map[string]enumNames      `json:"enums"`
	Orders     map[string][]string       `json:"orders"`
}

func main() {
	spec := flag.String("spec", "resources/openapi/nebula-openapi.json", "local OpenAPI 3.0 JSON file")
	names := flag.String("compat", "tools/nebula-gen/compat.json", "public Go naming overrides")
	out := flag.String("out", ".", "output directory")
	check := flag.Bool("check", false, "check generated files without writing them")
	flag.Parse()
	if err := run(*spec, *names, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "nebula-gen:", err)
		os.Exit(1)
	}
}

func run(specPath, namesPath, out string, check bool) error {
	data, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	doc, err := parseDocument(data)
	if err != nil {
		return err
	}
	data, err = os.ReadFile(namesPath)
	if err != nil {
		return err
	}
	var compat compatibility
	if err := json.Unmarshal(data, &compat); err != nil {
		return err
	}
	files, err := generate(doc, compat)
	if err != nil {
		return err
	}
	var stale []string
	entries, err := os.ReadDir(out)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		if _, generated := files[entry.Name()]; generated {
			continue
		}
		path := filepath.Join(out, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte("// Code generated by tools/nebula-gen ")) {
			if check {
				return fmt.Errorf("obsolete generated file: %s", entry.Name())
			}
			stale = append(stale, path)
		}
	}
	// Render and format everything before touching any output. Invalid schemas
	// therefore leave the last generated SDK intact.
	for _, name := range keys(files) {
		path := filepath.Join(out, name)
		old, readErr := os.ReadFile(path)
		if readErr != nil && !os.IsNotExist(readErr) {
			return readErr
		}
		if bytes.Equal(bytes.ReplaceAll(old, []byte("\r\n"), []byte("\n")), files[name]) {
			continue
		}
		if check {
			return fmt.Errorf("generated file is missing or stale: %s", name)
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(path, files[name], 0644); err != nil {
			return err
		}
	}
	for _, path := range stale {
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}
