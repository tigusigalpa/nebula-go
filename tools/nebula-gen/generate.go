package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strings"
)

type modelField struct {
	name, typ, jsonName, description string
	required                         bool
}
type model struct {
	name, group, signature string
	fields                 []modelField
	request, top           bool
}
type generator struct {
	doc    *document
	compat compatibility
	models map[string]*model
	refs   map[string]string
	enums  map[string]map[string]bool
	chunks map[string]*bytes.Buffer
	roots  map[string]bool
}

func generate(doc *document, compat compatibility) (map[string][]byte, error) {
	g := &generator{doc: doc, compat: compat, models: map[string]*model{}, refs: map[string]string{}, enums: map[string]map[string]bool{}, chunks: map[string]*bytes.Buffer{}, roots: map[string]bool{}}
	for _, op := range doc.ops {
		n := g.names(op)
		g.roots[n.Response] = true
	}
	for _, op := range doc.ops {
		n := g.names(op)
		response, ok := op.Responses["200"]
		if !ok {
			return nil, fmt.Errorf("%s: expected a 200 JSON response", op.ID)
		}
		s, err := doc.jsonSchema(response)
		if err != nil {
			return nil, fmt.Errorf("%s response: %w", op.ID, err)
		}
		if s.Type != "object" || len(s.Properties) == 0 {
			return nil, fmt.Errorf("%s: top-level response must be an object with fixed properties", op.ID)
		}
		if _, err := g.goType(s, op.ID+"/response", n.Response, n.Group, false); err != nil {
			return nil, err
		}
		if op.method == "get" {
			if err := g.query(op, n); err != nil {
				return nil, err
			}
		} else {
			if err := g.requestBody(op, n); err != nil {
				return nil, err
			}
		}
		g.service(op, n)
	}
	for _, name := range keys(g.models) {
		m := g.models[name]
		file := "models_" + m.group + ".go"
		if m.request {
			file = "request_" + m.group + ".go"
		}
		b := g.chunk(file)
		fmt.Fprintf(b, "// %s is a typed %s object.\ntype %s struct {\n", name, m.group, name)
		if m.top && !m.request {
			fmt.Fprintln(b, "BaseResponse")
		}
		for _, f := range m.fields {
			comment(b, f.description)
			if m.request && m.top {
				fmt.Fprintf(b, "%s %s\n", f.name, f.typ)
			} else {
				fmt.Fprintf(b, "%s %s `json:%q`\n", f.name, f.typ, f.jsonName)
			}
		}
		fmt.Fprint(b, "}\n\n")
	}
	g.enumTypes()
	if err := g.queryRules(); err != nil {
		return nil, err
	}
	g.eligibility()
	files := map[string][]byte{}
	for _, file := range keys(g.chunks) {
		body := g.chunks[file].String()
		var out bytes.Buffer
		fmt.Fprintf(&out, "// Code generated by tools/nebula-gen from OpenAPI %s (API %s); DO NOT EDIT.\n\npackage nebula\n\n", doc.OpenAPI, doc.Version)
		imports := []string{}
		parsed, err := parser.ParseFile(token.NewFileSet(), file, "package nebula\n"+body, 0)
		if err != nil {
			return nil, fmt.Errorf("parse generated %s: %w", file, err)
		}
		used := map[string]bool{}
		ast.Inspect(parsed, func(node ast.Node) bool {
			if selector, ok := node.(*ast.SelectorExpr); ok {
				if ident, ok := selector.X.(*ast.Ident); ok {
					used[ident.Name] = true
				}
			}
			return true
		})
		for _, pkg := range []string{"context", "fmt", "math", "net/url", "strconv", "strings", "time", "unicode/utf8"} {
			short := pkg[strings.LastIndex(pkg, "/")+1:]
			if used[short] {
				imports = append(imports, pkg)
			}
		}
		if len(imports) > 0 {
			fmt.Fprintln(&out, "import (")
			for _, pkg := range imports {
				fmt.Fprintf(&out, "%q\n", pkg)
			}
			fmt.Fprintln(&out, ")")
		}
		fmt.Fprint(&out, body)
		formatted, err := format.Source(out.Bytes())
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", file, err)
		}
		files[file] = formatted
	}
	return files, nil
}

func (g *generator) names(op *operation) operationNames {
	if n, ok := g.compat.Operations[op.ID]; ok {
		return n
	}
	group := "other"
	if len(op.Tags) > 0 {
		group = strings.ToLower(strings.ReplaceAll(op.Tags[0], " ", "_"))
	}
	base := goName(strings.TrimPrefix(strings.TrimPrefix(strings.TrimPrefix(op.ID, "get_"), "list_"), "create_"))
	return operationNames{Group: group, Service: goName(group), Method: base, Request: base + "Request", Response: base + "Response"}
}

func (g *generator) chunk(file string) *bytes.Buffer {
	if g.chunks[file] == nil {
		g.chunks[file] = &bytes.Buffer{}
	}
	return g.chunks[file]
}

func (g *generator) fieldName(parent, key string) string {
	if name := g.compat.Fields[parent+"."+key]; name != "" {
		return name
	}
	return goName(key)
}

func goName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool { return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') })
	for i, p := range parts {
		switch p {
		case "id":
			parts[i] = "ID"
		case "url":
			parts[i] = "URL"
		case "usd":
			parts[i] = "USD"
		default:
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	out := strings.Join(parts, "")
	if !token.IsIdentifier(out) {
		out = "Value" + out
	}
	return out
}

func comment(b *bytes.Buffer, text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		if line != "" {
			fmt.Fprintf(b, "// %s\n", strings.TrimSpace(line))
		}
	}
}

func (g *generator) goType(raw *schema, path, hint, group string, request bool) (string, error) {
	s, err := g.doc.resolve(raw)
	if err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	var typ string
	switch s.Type {
	case "string":
		typ = "string"
		if s.Format == "date-time" {
			typ = "time.Time"
		}
	case "integer":
		typ = "int"
		if s.Format == "int64" {
			typ = "int64"
		}
	case "number":
		typ = "float64"
	case "boolean":
		typ = "bool"
	case "array":
		child, err := g.goType(s.Items, path+"/items", hint+"Item", group, request)
		if err != nil {
			return "", err
		}
		typ = "[]" + child
	case "object":
		additional := string(s.AdditionalProperties)
		if len(s.Properties) > 0 && additional != "" && additional != "false" {
			return "", fmt.Errorf("%s: mixed fixed and dynamic object properties are unsupported", path)
		}
		if len(s.Properties) == 0 && additional != "false" {
			typ = "map[string]any"
			if additional != "" && additional != "true" {
				var value schema
				if err := json.Unmarshal(s.AdditionalProperties, &value); err != nil {
					return "", err
				}
				child, err := g.goType(&value, path+"/additionalProperties", hint+"Entry", group, request)
				if err != nil {
					return "", err
				}
				typ = "map[string]" + child
			}
			return typ, nil
		}
		typ = hint
		if raw.Ref != "" {
			if previous := g.refs[raw.Ref]; previous != "" {
				typ = previous
			} else {
				typ = goName(raw.Ref[strings.LastIndex(raw.Ref, "/")+1:])
			}
		}
		if name := g.compat.Objects[path]; name != "" {
			typ = name
		}
		if raw.Ref != "" {
			g.refs[raw.Ref] = typ
		}
		if !token.IsIdentifier(typ) {
			return "", fmt.Errorf("invalid Go type name %q", typ)
		}
		signature := schemaSignature(s)
		if m := g.models[typ]; m != nil {
			if m.signature != signature {
				return "", fmt.Errorf("%s: incompatible schemas share Go type %s; add a naming override", path, typ)
			}
		} else {
			m := &model{name: typ, group: group, signature: signature, request: request, top: g.roots[typ] || request && strings.HasSuffix(path, "/request")}
			g.models[typ] = m // Register before visiting recursive local references.
			for _, key := range keys(s.Properties) {
				p := s.Properties[key]
				fieldType, err := g.goType(p, path+"/properties/"+key, typ+goName(key), group, request)
				if err != nil {
					return "", err
				}
				required := contains(s.Required, key)
				resolved, err := g.doc.resolve(p)
				if err != nil {
					return "", err
				}
				if !required || resolved.Type == "object" {
					fieldType = optional(fieldType)
				}
				m.fields = append(m.fields, modelField{g.fieldName(typ, key), fieldType, key, p.Description, required})
			}
			g.orderFields(m)
		}
	default:
		return "", fmt.Errorf("%s: unsupported or missing schema type %q", path, s.Type)
	}
	if alias := g.compat.Scalars[path]; alias != "" {
		if s.Type != "string" || s.Format == "date-time" {
			return "", fmt.Errorf("%s: scalar naming override %s no longer matches a string schema", path, alias)
		}
		typ = alias
		if g.enums[alias] == nil {
			g.enums[alias] = map[string]bool{}
		}
		for _, value := range s.Enum {
			if value == nil && s.Nullable {
				continue
			}
			v, ok := value.(string)
			if !ok {
				return "", fmt.Errorf("%s: non-string enum", path)
			}
			g.enums[alias][v] = true
		}
	}
	if s.Nullable {
		typ = optional(typ)
	}
	return typ, nil
}

func optional(typ string) string {
	if strings.HasPrefix(typ, "*") || strings.HasPrefix(typ, "[]") || strings.HasPrefix(typ, "map[") {
		return typ
	}
	return "*" + typ
}

// Description/example/default differences do not change a shared Go layout.
func schemaSignature(s *schema) string {
	b, _ := json.Marshal(s)
	var value any
	_ = json.Unmarshal(b, &value)
	var clean func(any)
	clean = func(v any) {
		switch x := v.(type) {
		case map[string]any:
			delete(x, "description")
			for _, c := range x {
				clean(c)
			}
		case []any:
			for _, c := range x {
				clean(c)
			}
		}
	}
	clean(value)
	b, _ = json.Marshal(value)
	return string(b)
}

func (g *generator) enumTypes() {
	b := g.chunk("enums_generated.go")
	for _, name := range keys(g.enums) {
		fmt.Fprintf(b, "// %s contains the values documented by the OpenAPI contract.\ntype %s string\nconst (\n", name, name)
		for _, value := range keys(g.enums[name]) {
			constant := g.compat.Enums[name].Constants[value]
			if constant == "" {
				constant = name + goName(value)
			}
			fmt.Fprintf(b, "%s %s = %q\n", constant, name, value)
		}
		fmt.Fprint(b, ")\n\n")
	}
}

func (g *generator) service(op *operation, n operationNames) {
	b := g.chunk("service_" + n.Group + ".go")
	comment(b, n.Method+" calls "+strings.ToUpper(op.method)+" "+op.path+". "+op.Summary)
	if op.External.URL != "" {
		comment(b, "Docs: "+op.External.URL)
	}
	if op.method == "get" {
		arg, req := "", "nil"
		if len(op.Parameters) > 0 {
			arg = ", req *" + n.Request
			req = "req"
		}
		fmt.Fprintf(b, "func (s *%sService) %s(ctx context.Context%s) (*%s,error) {\nreturn get[%s](ctx,s.client,%q,%s,%q)\n}\n\n", n.Service, n.Method, arg, n.Response, n.Response, op.path, req, op.ID)
	} else {
		fmt.Fprintf(b, "func (s *%sService) %s(ctx context.Context, req *%s) (*%s,error) {\nif err:=req.validate();err!=nil{return nil,err}\nreturn postJSON[%s](ctx,s.client,%q,req.body(false),%q)\n}\n\n", n.Service, n.Method, n.Request, n.Response, n.Response, op.path, op.ID)
		fmt.Fprintf(b, "// StreamChatCompletion returns a closeable server-sent-events stream.\nfunc(s *%sService) StreamChatCompletion(ctx context.Context, req *%s)(*ChatStream,error){\nif err:=req.validate();err!=nil{return nil,err}\nreturn streamSSE(ctx,s.client,%q,req.body(true),%q)\n}\n\n", n.Service, n.Request, op.path, op.ID)
	}
}

func (g *generator) eligibility() {
	b := g.chunk("x402eligible.go")
	fmt.Fprintln(b, "var x402EligibleOps = map[string]bool{")
	for _, op := range g.doc.ops {
		if op.X402 {
			if op.method != "get" {
				continue
			}
			fmt.Fprintf(b, "%q:true,\n", op.ID)
		}
	}
	fmt.Fprintln(b, "}\nfunc x402Eligible(op string) bool {return x402EligibleOps[op]}\n\n// X402Eligible reports whether the operation is served on the x402 surface.\nfunc X402Eligible(op string) bool {return x402Eligible(op)}")
}

func (g *generator) orderFields(m *model) {
	order := g.compat.Orders[m.name]
	index := func(name string) int {
		for i, n := range order {
			if name == n {
				return i
			}
		}
		return len(order)
	}
	sort.SliceStable(m.fields, func(i, j int) bool { return index(m.fields[i].name) < index(m.fields[j].name) })
}
