func TestInvalidContractLeavesOutputIntact(t *testing.T) {
	_, _, spec, names := pinned(t)
	data, err := os.ReadFile(spec)
	if err != nil {
		t.Fatal(err)
	}
	var root map[string]any
	if err := json.Unmarshal(data, &root); err != nil {
		t.Fatal(err)
	}
	last := root["paths"].(map[string]any)["/top-trending"].(map[string]any)["get"].(map[string]any)
	props := last["responses"].(map[string]any)["200"].(map[string]any)["content"].(map[string]any)["application/json"].(map[string]any)["schema"].(map[string]any)["properties"].(map[string]any)
	props["unsupported"] = map[string]any{"type": "unknown"}
	modified := filepath.Join(t.TempDir(), "invalid.json")
	data, err = json.Marshal(root)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(modified, data, 0644); err != nil {
		t.Fatal(err)
	}
	out := t.TempDir()
	sentinel := filepath.Join(out, "models_lookup.go")
	if err := os.WriteFile(sentinel, []byte("preserve this output"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := run(modified, names, out, false); err == nil {
		t.Fatal("invalid contract accepted")
	}
	actual, err := os.ReadFile(sentinel)
	if err != nil || string(actual) != "preserve this output" {
		t.Fatal("invalid generation overwrote existing output")
	}
	entries, err := os.ReadDir(out)
	if err != nil || len(entries) != 1 {
		t.Fatal("invalid generation left partial output")
	}
}
