func pinned(t *testing.T) (*document, compatibility, string, string) {
	t.Helper()
	spec := filepath.Join("..", "..", "resources", "openapi", "nebula-openapi.json")
	names := "compat.json"
	data, err := os.ReadFile(spec)
	if err != nil {
		t.Fatal(err)
	}
	doc, err := parseDocument(data)
	if err != nil {
		t.Fatal(err)
	}
	data, err = os.ReadFile(names)
	if err != nil {
		t.Fatal(err)
	}
	var compat compatibility
	if err := json.Unmarshal(data, &compat); err != nil {
		t.Fatal(err)
	}
	return doc, compat, spec, names
}

func TestPinnedGenerationFromScratch(t *testing.T) {
	doc, compat, spec, names := pinned(t)
	first, err := generate(doc, compat)
	if err != nil {
		t.Fatal(err)
	}
	second, err := generate(doc, compat)
	if err != nil {
		t.Fatal(err)
	}
	for name, data := range first {
		if !bytes.Equal(data, second[name]) {
			t.Fatalf("nondeterministic %s", name)
		}
	}
	out := t.TempDir()
	if err := run(spec, names, out, false); err != nil {
		t.Fatal(err)
	}
	if err := run(spec, names, out, true); err != nil {
		t.Fatal(err)
	}
	if err := run(spec, names, filepath.Join("..", ".."), true); err != nil {
		t.Fatal(err)
	}
	for name, data := range first {
		actual, err := os.ReadFile(filepath.Join(out, name))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(data, actual) {
			t.Fatalf("cold generation differs for %s", name)
		}
	}

	changed := filepath.Join(out, "models_lookup.go")
	modified := append(append([]byte{}, first["models_lookup.go"]...), []byte("// edited\n")...)
	if err := os.WriteFile(changed, modified, 0644); err != nil {
		t.Fatal(err)
	}
	if err := run(spec, names, out, true); err == nil {
		t.Fatal("check accepted an edited model")
	}
	actual, _ := os.ReadFile(changed)
	if !bytes.Equal(modified, actual) {
		t.Fatal("check mode changed a file")
	}
	if err := run(spec, names, out, false); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(out, "models_removed.go")
	if err := os.WriteFile(stale, []byte("// Code generated by tools/nebula-gen from an old contract; DO NOT EDIT.\npackage nebula\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := run(spec, names, out, true); err == nil {
		t.Fatal("check accepted obsolete generated output")
	}
	if err := run(spec, names, out, false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("obsolete output was not removed")
	}
}

// Pin exported layouts, field order, tags and enum values from the released
// v0.2.0 SDK. This catches changes that JSON-only contract tests cannot see.
func TestPublicAPICompatibility(t *testing.T) {
	doc, compat, _, _ := pinned(t)
	files, err := generate(doc, compat)
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"enums.go", "model_compat.go"} {
		files[name], err = os.ReadFile(filepath.Join("..", "..", name))
		if err != nil {
			t.Fatal(err)
		}
	}
	var baseline struct{ Types, Constants map[string]string }
	data, err := os.ReadFile("testdata/public-api-v0.2.0.json")
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, &baseline); err != nil {
		t.Fatal(err)
	}
	types, constants := map[string]string{}, map[string]string{}
	for name, source := range files {
		file, err := parser.ParseFile(token.NewFileSet(), name, source, 0)
		if err != nil {
			t.Fatal(err)
		}
		for _, declaration := range file.Decls {
			decl, ok := declaration.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range decl.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if !s.Name.IsExported() {
						continue
					}
					if st, ok := s.Type.(*ast.StructType); ok {
						fields := []string{}
						for _, f := range st.Fields.List {
							tag := ""
							if f.Tag != nil {
								tag = strings.Trim(f.Tag.Value, "`")
							}
							fieldName := ""
							if len(f.Names) > 0 {
								fieldName = f.Names[0].Name
							}
							fields = append(fields, fieldName+":"+exprText(f.Type)+":"+tag)
						}
						types[s.Name.Name] = strings.Join(fields, "|")
					} else {
						types[s.Name.Name] = "=" + exprText(s.Type)
					}
				case *ast.ValueSpec:
					if decl.Tok != token.CONST || len(s.Values) != 1 {
						continue
					}
					alias := ""
					if s.Type != nil {
						alias = exprText(s.Type)
					}
					constants[s.Names[0].Name] = alias + ":" + exprText(s.Values[0])
				}
			}
		}
	}
	for name, expected := range baseline.Types {
		if actual, ok := types[name]; !ok || actual != expected {
			t.Errorf("public type %s changed:\nwant %s\ngot  %s", name, expected, actual)
		}
	}
	for name, expected := range baseline.Constants {
		if actual, ok := constants[name]; !ok || actual != expected {
			t.Errorf("public constant %s changed: want %s, got %s", name, expected, actual)
		}
	}
}

func exprText(expr ast.Expr) string {
	var b bytes.Buffer
	_ = format.Node(&b, token.NewFileSet(), expr)
	return b.String()
}

func TestLocalReferencesAndUnsupportedSchemas(t *testing.T) {
	base := `{"openapi":"3.0.3","info":{"version":"test"},"paths":{"/widgets":{"parameters":[{"$ref":"#/components/parameters/Count"}],"get":{"operationId":"widgets","tags":["Widgets"],"responses":{"200":{"$ref":"#/components/responses/Widgets"}}}}},"components":{"parameters":{"Count":{"in":"query","name":"count","schema":{"type":"integer","minimum":1}}},"responses":{"Widgets":{"content":{"application/json":{"schema":{"type":"object","properties":{"node":{"$ref":"#/components/schemas/Node"}}}}}}},"schemas":{"Node":{"type":"object","properties":{"children":{"type":"array","items":{"$ref":"#/components/schemas/Node"}},"counts":{"type":"object","additionalProperties":{"type":"integer","format":"int64"}}}}}}}`
	doc, err := parseDocument([]byte(base))
	if err != nil {
		t.Fatal(err)
	}
	files, err := generate(doc, compatibility{})
	if err != nil {
		t.Fatal(err)
	}
	source := string(files["models_widgets.go"])
	for _, fragment := range []string{"[]Node", "map[string]int64", "Node *Node"} {
		if !strings.Contains(source, fragment) {
			t.Errorf("generated models lack %q", fragment)
		}
	}
	for _, bad := range []string{
		strings.Replace(base, `"#/components/schemas/Node"`, `"https://example.invalid/schema.json"`, 1),
		strings.Replace(base, `"#/components/schemas/Node"`, `"#/components/schemas/Missing"`, 1),
		strings.Replace(base, `"minimum":1`, `"oneOf":[]`, 1),
		strings.Replace(base, `"in":"query"`, `"in":"path"`, 1),
	} {
		doc, err := parseDocument([]byte(bad))
		if err == nil {
			_, err = generate(doc, compatibility{})
		}
		if err == nil {
			t.Error("unsupported contract was silently accepted")
		}
	}
}

// Mutate the contract, generate into an empty module, and run code against the
// resulting SDK. No old generated file or model template is available there.
func TestSchemaChangesProduceWorkingSDK(t *testing.T) {
	_, _, spec, names := pinned(t)
	data, err := os.ReadFile(spec)
	if err != nil {
		t.Fatal(err)
	}
	var root map[string]any
	if err := json.Unmarshal(data, &root); err != nil {
		t.Fatal(err)
	}
	paths := root["paths"].(map[string]any)
	assets := paths["/assets"].(map[string]any)["get"].(map[string]any)
	assets["parameters"] = append(assets["parameters"].([]any), map[string]any{"name": "trace_id", "in": "query", "schema": map[string]any{"type": "integer", "format": "int64", "minimum": 1}}, map[string]any{"name": "modes", "in": "query", "explode": false, "schema": map[string]any{"type": "array", "minItems": 1, "maxItems": 2, "items": map[string]any{"type": "integer", "enum": []int{1, 2, 3}}}})
	for _, raw := range assets["parameters"].([]any) {
		p := raw.(map[string]any)
		if p["name"] == "asset_class" {
			s := p["schema"].(map[string]any)
			s["enum"] = append(s["enum"].([]any), "forex")
		}
	}
	props := assets["responses"].(map[string]any)["200"].(map[string]any)["content"].(map[string]any)["application/json"].(map[string]any)["schema"].(map[string]any)["properties"].(map[string]any)
	var probe map[string]any
	if err := json.Unmarshal([]byte(`{"type":"object","nullable":true,"properties":{"count":{"type":"integer","format":"int64"},"at":{"type":"string","format":"date-time","nullable":true},"weights":{"type":"object","additionalProperties":{"type":"number","format":"double"}},"events":{"type":"array","items":{"type":"object","properties":{"active":{"type":"boolean"}},"required":["active"]}}},"required":["count","weights","events"]}`), &probe); err != nil {
		t.Fatal(err)
	}
	props["probe"] = probe
	predictions := paths["/predictions"].(map[string]any)["get"].(map[string]any)
	for _, raw := range predictions["parameters"].([]any) {
		p := raw.(map[string]any)
		if p["name"] == "provider" {
			s := p["schema"].(map[string]any)
			s["enum"] = append(s["enum"].([]any), "example_venue")
		}
	}
	chat := paths["/chat/completions"].(map[string]any)["post"].(map[string]any)
	bodyProps := chat["requestBody"].(map[string]any)["content"].(map[string]any)["application/json"].(map[string]any)["schema"].(map[string]any)["properties"].(map[string]any)
	var metadata map[string]any
	if err := json.Unmarshal([]byte(`{"type":"object","properties":{"title":{"type":"string","minLength":1},"count":{"type":"integer","minimum":0,"maximum":2},"tags":{"type":"array","minItems":1,"items":{"type":"string","minLength":1}}},"required":["title"]}`), &metadata); err != nil {
		t.Fatal(err)
	}
	bodyProps["metadata"] = metadata
	data, err = json.Marshal(root)
	if err != nil {
		t.Fatal(err)
	}
	out := t.TempDir()
	modified := filepath.Join(t.TempDir(), "openapi.json")
	if err := os.WriteFile(modified, data, 0644); err != nil {
		t.Fatal(err)
	}
	if err := run(modified, names, out, false); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		source, err := os.ReadFile(filepath.Join("..", "..", name))
		if err != nil {
			t.Fatal(err)
		}
		if bytes.HasPrefix(source, []byte("// Code generated")) {
			continue
		}
		if err := os.WriteFile(filepath.Join(out, name), source, 0644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(out, "go.mod"), []byte("module generatedsdk\n\ngo 1.24.0\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(out, "evolution_test.go"), []byte(evolutionTest), 0644); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "test", ".", "-count=1")
	cmd.Dir = out
	// Use the toolchain running this test, including an automatically selected
	// toolchain that differs from the Go launcher found on PATH.
	cmd.Env = append(os.Environ(), "GOTOOLCHAIN="+runtime.Version(), "GOWORK=off", "GOPROXY=off", "GOSUMDB=off")
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated SDK does not work: %v\n%s", err, output)
	}
}

